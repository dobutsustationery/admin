#!/usr/bin/env node

/**
 * Prepares Firebase Functions dotenv file from a root environment file.
 *
 * Usage:
 *   node scripts/prepare-functions-env.js local
 *   node scripts/prepare-functions-env.js staging
 *   node scripts/prepare-functions-env.js production
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { resolve } from "path";
import { execSync } from "child_process";

const VALID_ENVS = ["local", "staging", "production"];
const env = process.argv[2];

if (!env || !VALID_ENVS.includes(env)) {
  console.log("Usage: node scripts/prepare-functions-env.js [local|staging|production]");
  process.exit(1);
}

const sourceMap = {
  local: ".env.emulator",
  staging: ".env.staging",
  production: ".env.production",
};

const sourcePath = resolve(process.cwd(), sourceMap[env]);
const functionsDir = resolve(process.cwd(), "functions");
const targetPath = resolve(functionsDir, ".env");

if (!existsSync(sourcePath)) {
  console.error(`Missing source env file: ${sourceMap[env]}`);
  console.error("Create it first (it is intentionally gitignored).");
  process.exit(1);
}

const source = readFileSync(sourcePath, "utf8");
const lines = source
  .split(/\r?\n/)
  .map((line) => line.trimEnd())
  .filter((line) => line && !line.trimStart().startsWith("#"))
  .filter((line) => line.includes("="));

const keepPrefixes = ["SHOPIFY_", "FIREBASE_", "GOOGLE_APPLICATION_CREDENTIALS"];
const kept = lines.filter((line) => {
  const key = line.split("=")[0]?.trim() || "";
  if (!key) return false;
  return keepPrefixes.some((prefix) => key.startsWith(prefix));
});

if (kept.length === 0) {
  console.error(`No supported function env vars found in ${sourceMap[env]}.`);
  console.error(
    "Expected SHOPIFY_STORE_URL and either SHOPIFY_ACCESS_TOKEN or SHOPIFY_CLIENT_ID/SHOPIFY_CLIENT_SECRET.",
  );
  process.exit(1);
}

mkdirSync(functionsDir, { recursive: true });
writeFileSync(
  targetPath,
  [
    `# Generated by scripts/prepare-functions-env.js from ${sourceMap[env]}`,
    `# Environment: ${env}`,
    ...kept,
    "",
  ].join("\n"),
  "utf8",
);

// DEDUPLICATION: Generate CommonJS bridge for shared idempotency logic
const idempotencySource = resolve(process.cwd(), "src/lib/idempotency-utils.ts");
const idempotencyTarget = resolve(functionsDir, "shared/idempotency-utils.cjs");
if (existsSync(idempotencySource)) {
  try {
    execSync(`npx esbuild "${idempotencySource}" --bundle --platform=node --format=cjs --outfile="${idempotencyTarget}"`);
    console.log(`Generated ${idempotencyTarget} from ${idempotencySource} using esbuild.`);
  } catch (e) {
    console.error("Failed to generate idempotency-utils.cjs:", e.message);
  }
}

console.log(`Prepared functions/.env from ${sourceMap[env]} (${kept.length} vars).`);
