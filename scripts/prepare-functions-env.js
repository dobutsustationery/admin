#!/usr/bin/env node

/**
 * Prepares Firebase Functions dotenv file from a root environment file.
 *
 * Usage:
 *   node scripts/prepare-functions-env.js local
 *   node scripts/prepare-functions-env.js staging
 *   node scripts/prepare-functions-env.js production
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { resolve } from "path";
import { execSync } from "child_process";

const VALID_ENVS = ["local", "staging", "production"];
const env = process.argv[2];

if (!env || !VALID_ENVS.includes(env)) {
  console.log(
    "Usage: node scripts/prepare-functions-env.js [local|staging|production]",
  );
  process.exit(1);
}

const sourceMap = {
  local: ".env.emulator",
  staging: ".env.staging",
  production: ".env.production",
};

const sourcePath = resolve(process.cwd(), sourceMap[env]);
const functionsDir = resolve(process.cwd(), "functions");
const targetPath = resolve(functionsDir, ".env");

let kept = [];
const keepPrefixes = [
  "SHOPIFY_",
  "FIREBASE_",
  "GOOGLE_APPLICATION_CREDENTIALS",
  "GOOGLE_OAUTH_",
  "E2E_GOOGLE_",
];
const keepExactKeys = [
  "VITE_GOOGLE_DRIVE_CLIENT_ID",
  "VITE_GOOGLE_PHOTOS_CLIENT_ID",
];

function shouldKeepKey(key) {
  return (
    keepExactKeys.includes(key) ||
    keepPrefixes.some((prefix) => key.startsWith(prefix))
  );
}

if (!existsSync(sourcePath)) {
  if (process.env.CI) {
    console.log(
      `⚠️ Missing source env file ${sourceMap[env]} in CI. Falling back to environment variables.`,
    );
    // In CI, we extract from process.env instead of a file
    for (const key in process.env) {
      if (shouldKeepKey(key)) {
        kept.push(`${key}=${process.env[key]}`);
      }
    }
  } else {
    console.error(`Missing source env file: ${sourceMap[env]}`);
    console.error("Create it first (it is intentionally gitignored).");
    process.exit(1);
  }
} else {
  const source = readFileSync(sourcePath, "utf8");
  const lines = source
    .split(/\r?\n/)
    .map((line) => line.trimEnd())
    .filter((line) => line && !line.trimStart().startsWith("#"))
    .filter((line) => line.includes("="));

  kept = lines.filter((line) => {
    const key = line.split("=")[0]?.trim() || "";
    if (!key) return false;
    return shouldKeepKey(key);
  });
}

if (kept.length === 0) {
  if (process.env.CI) {
    console.warn(
      `⚠️ No supported function env vars found in environment. Sync functions might fail.`,
    );
    // Create an empty .env file to allow emulators to start anyway
    kept = ["# Empty .env for CI fallback"];
  } else {
    console.error(`No supported function env vars found in ${sourceMap[env]}.`);
    console.error(
      "Expected Shopify vars and Google OAuth vars (GOOGLE_OAUTH_* or VITE_GOOGLE_*_CLIENT_ID).",
    );
    process.exit(1);
  }
}

mkdirSync(functionsDir, { recursive: true });
writeFileSync(
  targetPath,
  [
    `# Generated by scripts/prepare-functions-env.js from ${sourceMap[env]}`,
    `# Environment: ${env}`,
    ...kept,
    "",
  ].join("\n"),
  "utf8",
);

// DEDUPLICATION: Generate CommonJS bridge for shared idempotency logic
const idempotencySource = resolve(
  process.cwd(),
  "src/lib/idempotency-utils.ts",
);
const idempotencyTarget = resolve(functionsDir, "shared/idempotency-utils.cjs");
try {
  if (existsSync(idempotencySource)) {
    execSync(
      `npx esbuild "${idempotencySource}" --bundle --platform=node --format=cjs --outfile="${idempotencyTarget}"`,
    );
    console.log(
      `Generated ${idempotencyTarget} from ${idempotencySource} using esbuild.`,
    );
  }
} catch (e) {
  console.error("Failed to generate idempotency-utils.cjs:", e.message);
}

console.log(
  `Prepared functions/.env from ${sourceMap[env]} (${kept.length} vars).`,
);
